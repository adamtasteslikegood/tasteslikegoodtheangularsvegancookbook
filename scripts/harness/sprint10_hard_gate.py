#!/usr/bin/env python3
"""Sprint 10 HARD GATE — no committed Sprint 10 item may sit in To Do.

Sprint 10 successor of ``sprint9_hard_gate.py`` (same rules, Sprint 10
constants), plus ``--charter``: the day-1 form named by RCP-99. It runs
rules 1, 2 and 4 and requires the sprint to be ``active``; it skips rule 3,
because on day 1 every item is legitimately in To Do. ``--charter`` proves
the board is honest at charter time; the full gate is the close gate.

This is the gate the Sprint 10 close is judged by. It is read-only and
lives in its own file on purpose: nothing that can move an issue shares a module
with the check that reads it. Do not edit this file to make a run pass — that is
the reward-hacking failure mode the harness exists to prevent. If the gate is
wrong, change it in its own commit, with a reason, before the run that needs it.

The rule
--------
Exit 0 only when ALL of these hold:

1. **Sprint 10 exists** on the RCP scrum board and is ``active`` or ``closed``.
   Without this, "no sprint" would mean "no items" would mean "gate passes" —
   the vacuous pass the Sprint 9 charter names in R2.
2. **Every non-droppable committed item is a sprint member.** Otherwise the gate
   could be satisfied by emptying the sprint.
3. **No committed item that is in the sprint sits in the To Do status
   category.** Done, In Progress and In Review all pass — matching the sprint's
   definition of done: every item is delivered, in review, or consciously
   dropped.
4. **Every committed SI has an RCP acceptance row the BOARD ACTUALLY RENDERS.**
   Added 2026-09-01 (KAN-260) after this gate reported PASS for four days on a
   sprint the RCP board displayed as a single row.

Rule 4, and why it is not a member/rendered delta
-------------------------------------------------
Board 168's filter is ``project = RCP ORDER BY Rank ASC``. KAN is a separate,
team-managed project, so **a KAN key added to this sprint is a member that no
column can ever show.** ``/rest/agile/1.0/sprint/{id}/issue`` returns membership
and ignores the filter; ``/rest/agile/1.0/board/{b}/sprint/{id}/issue`` returns
what is rendered. Rules 2 and 3 read the first endpoint only, so they were blind
to a board with nothing on it.

The obvious repair — diff the two endpoints, fail on the delta — is **wrong, and
would be red on the one sprint that got this right.** Sprint 8 is 13 members and
6 rendered: its KAN execution rows are *supposed* to be members (rule 2 demands
it) and structurally cannot render, and its epic renders in the epic panel
rather than a column. A delta rule would also reward deleting KAN rows from the
sprint, which breaks rule 2.

So rule 4 asserts what Sprint 8 actually did: **one RCP ``S<N> acceptance:``
Story per SI, present in the board-scoped result.** The epic is never required
there. A D6-dropped SI is exempt, exactly as it is under rule 3.

Droppable items
---------------
Sprint 10 pre-authorises none. Adam's 2026-09-29 cuts (grill rows #4, #11, #12)
happened before the charter, so those items were never committed. Dropping a
committed item requires a charter update, not a gate edit.

What this gate does NOT prove
-----------------------------
Status alone is weak evidence. A Jira global rule still moves a ticket
``To Do -> In Progress`` when a branch is created for it, so an item can leave
To Do without any work happening. That is why each harness task carries its own
artifact check (PR state, CI rollup) and a named-evidence requirement on top of
this gate. Passing here means the board is honest, not that the sprint is done.

Usage
-----
    python3 scripts/harness/sprint10_hard_gate.py            # full (close) gate
    python3 scripts/harness/sprint10_hard_gate.py --charter  # day-1 gate
    python3 scripts/harness/sprint10_hard_gate.py --issues KAN-268
    python3 scripts/harness/sprint10_hard_gate.py --json

Exit codes: 0 pass · 1 gate failed · 2 configuration or API error.
"""

