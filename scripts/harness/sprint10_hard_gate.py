# Sprint 10 pre-authorises no drops. S3's "evidence-only" flip changes how S3
# closes, not whether it is in the sprint. Dropping anything is a charter update.
DROPPABLE_SIS = set()
DROPPABLE = {}

COMMITTED = dict(REQUIRED, **DROPPABLE)
TODO_CATEGORY_KEYS = {"new", "undefined"}


def is_todo(fields):
    cat = fields["status"].get("statusCategory") or {}
    if cat.get("key"):
        return cat["key"].lower() in TODO_CATEGORY_KEYS
    return (cat.get("name") or "").strip().lower() == "to do"


def main():
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = p.add_mutually_exclusive_group()
    mode.add_argument("--issues", nargs="+", default=None,
                      help="scoped check: only these keys must be out of To Do "
                           "(skips the sprint-membership rules)")
    mode.add_argument("--charter", action="store_true",
                      help="day-1 gate: rules 1, 2, 4 with the sprint active; "
                           "skips rule 3 (To Do)")
    p.add_argument("--json", action="store_true", help="machine-readable output")
    args = p.parse_args()

    try:
        jira = Jira()
    except (SystemExit, AtlassianGuardError) as exc:
        # SystemExit covers missing creds; AtlassianGuardError covers a
        # disallowed ATLASSIAN_URL (e.g. the -dev service site). Both are
        # configuration errors and must funnel to exit-2, per the docstring.
        print("CONFIG ERROR: %s" % exc, file=sys.stderr)
        return 2

    gate = (
        "sprint10-charter" if args.charter
        else "sprint10-scoped-status" if args.issues is not None
        else "sprint10-no-todo"
    )
    report = {"gate": gate, "checks": [], "violations": [], "passed": False}
    status_descriptions = dict(COMMITTED)

    try:
        if args.issues:
            scope = list(args.issues)
        else:
            sprint = next((s for s in jira.sprints(RCP_SCRUM_BOARD)
                           if s["name"].strip().lower() == SPRINT_NAME.lower()), None)
            if not sprint:
                report["violations"].append(
                    "Sprint 10 does not exist on board %d — a missing sprint is a "
                    "vacuous pass, not a pass" % RCP_SCRUM_BOARD)
                return finish(report, args)
            report["sprint"] = {"id": sprint["id"], "state": sprint["state"]}
            allowed = ("active",) if args.charter else ("active", "closed")
            if sprint["state"] not in allowed:
                report["violations"].append(
                    "Sprint 10 is %r; expected %s" % (sprint["state"], " or ".join(allowed)))
            members = {i["key"] for i in jira.sprint_issues(sprint["id"])}
            report["member_count"] = len(members)
            for key, what in sorted(REQUIRED.items()):
                if key not in members:
                    report["violations"].append(
                        "%s is not in Sprint 10 (%s) — required items cannot be "
                        "dropped without a charter update" % (key, what))
            report["dropped"] = sorted(k for k in DROPPABLE if k not in members)

            # Rule 4 — board visibility. Read what the BOARD renders, not what the
            # sprint contains; the module docstring explains why this is not a
            # member/rendered delta.
            rendered = {i["key"] for i in
                        jira.board_sprint_issues(RCP_SCRUM_BOARD, sprint["id"])}
            report["board_rendered"] = sorted(rendered)
            report["acceptance"] = {}
            active_acceptance = {}
            for si in sorted(SI_EXECUTION):
                dropped = not any(k in members for k in SI_EXECUTION[si])
                row = ACCEPTANCE.get(si)
                if dropped and si in DROPPABLE_SIS:
                    if not row:
                        report["acceptance"][si] = "dropped — MISSING MAPPING"
                        report["violations"].append(
                            "%s is treated as dropped but has no acceptance-row "
                            "mapping, so the gate cannot prove the SI was removed "
                            "as a unit" % si)
                    elif row in members or row in rendered:
                        report["acceptance"][si] = "STRANDED — %s" % row
                        report["violations"].append(
                            "%s is treated as dropped because execution row(s) %s "
                            "left Sprint 10, but acceptance row %s remains in the "
                            "sprint/board — remove the SI as a unit"
                            % (si, "/".join(SI_EXECUTION[si]), row))
                    else:
                        report["acceptance"][si] = "dropped"
                    continue
                report["acceptance"][si] = row
                if not row:
                    report["violations"].append(
                        "%s has no RCP acceptance row — board %d filters "
                        "`project = RCP`, so its execution row(s) %s are sprint "
                        "members that no column renders"
                        % (si, RCP_SCRUM_BOARD, "/".join(SI_EXECUTION[si])))
                elif row not in rendered:
                    report["violations"].append(
                        "%s's acceptance row %s is not rendered by board %d for "
                        "this sprint — add it to the sprint, or the item is "
                        "invisible on the board" % (si, row, RCP_SCRUM_BOARD))
                else:
                    active_acceptance[row] = "%s — board-visible acceptance" % si

            # Acceptance rows are first-class committed sprint artifacts too;
            # rule 3 must reject one left in To Do just like its execution row.
            # Use setdefault so a row already described by COMMITTED keeps its
            # more specific charter/timebox context.
            for k, v in active_acceptance.items():
                status_descriptions.setdefault(k, v)
            scope = ({k for k in COMMITTED if k in members}
                     | {k for k in active_acceptance if k in members})

        if args.charter:
            scope = []  # rule 3 is the close gate; day 1 is all To Do by design
        for key in sorted(scope):
            f = jira.issue(key, fields="summary,status")["fields"]
            todo = is_todo(f)
            report["checks"].append({
                "key": key, "status": f["status"]["name"],
                "category": (f["status"].get("statusCategory") or {}).get("name"),
                "todo": todo,
            })
            if todo:
                report["violations"].append(
                    "%s is in To Do (%s) — %s"
                    % (key, f["status"]["name"],
                       status_descriptions.get(key, "scoped check")))
    except RuntimeError as exc:
        print("API ERROR: %s" % exc, file=sys.stderr)
        return 2

    return finish(report, args)


def finish(report, args):
    report["passed"] = not report["violations"]
    if args.json:
        print(json.dumps(report, indent=2))
    else:
        for c in report["checks"]:
            print("%-9s %-14s %s" % (c["key"], c["status"], "TO DO" if c["todo"] else "ok"))
        for si, row in sorted(report.get("acceptance", {}).items()):
            print("%-9s %-14s %s" % (si, "acceptance",
                                     row if row else "MISSING — no RCP row"))
        for d in report.get("dropped", []):
            print("%-9s %-14s dropped from sprint (D6 timebox) — exempt"
                  % (d, "-"))
        if report["violations"]:
            print("\nHARD GATE FAILED — %d violation(s):" % len(report["violations"]))
            for v in report["violations"]:
                print("  - %s" % v)
        elif report["gate"] == "sprint10-scoped-status":
            print("\nSCOPED CHECK PASSED — every requested issue is out of To Do.")
        else:
            print("\nHARD GATE PASSED — every committed Sprint 10 item is %s AND has an "
                  "acceptance row the board renders." % (
                      "a member of the active sprint"
                      if report["gate"] == "sprint10-charter"
                      else "out of To Do"))
    return 0 if report["passed"] else 1


if __name__ == "__main__":
    sys.exit(main())
